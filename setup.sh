#!/usr/bin/env bash
# Setup script for daVinci-MagiHuman on macOS Apple Silicon
# Downloads model weights to HuggingFace cache (~190 GB total)

set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$PROJECT_ROOT"

LOG_FILE="$PROJECT_ROOT/setup_download.log"
PATHS_FILE="$PROJECT_ROOT/model_paths.env"

# Timestamp helper
ts() { date '+%Y-%m-%d %H:%M:%S'; }

# Log to both console and file
log() { echo "[$(ts)] $*" | tee -a "$LOG_FILE"; }
log_header() {
    echo "" | tee -a "$LOG_FILE"
    echo "============================================================" | tee -a "$LOG_FILE"
    echo "[$(ts)] $*" | tee -a "$LOG_FILE"
    echo "============================================================" | tee -a "$LOG_FILE"
}
log_step() {
    echo "" | tee -a "$LOG_FILE"
    echo "------------------------------------------------------------" | tee -a "$LOG_FILE"
    echo "[$(ts)] $*" | tee -a "$LOG_FILE"
    echo "------------------------------------------------------------" | tee -a "$LOG_FILE"
}

# Track timing
SCRIPT_START=$(date +%s)
step_start() { STEP_START=$(date +%s); }
step_elapsed() {
    local elapsed=$(( $(date +%s) - STEP_START ))
    local min=$((elapsed / 60))
    local sec=$((elapsed % 60))
    echo "${min}m ${sec}s"
}
total_elapsed() {
    local elapsed=$(( $(date +%s) - SCRIPT_START ))
    local min=$((elapsed / 60))
    local sec=$((elapsed % 60))
    echo "${min}m ${sec}s"
}

log_header "daVinci-MagiHuman — Model Download Setup"
log "Using HuggingFace cache (no local copies)"
log "Log file: $LOG_FILE"

# Activate venv if exists
if [ -f ".venv/bin/activate" ]; then
    source .venv/bin/activate
    log "Activated venv: $(python3 --version)"
fi

# Ensure hf CLI is available
if ! command -v hf &>/dev/null; then
    log "hf CLI not found. Installing huggingface-hub[cli]..."
    pip install "huggingface-hub[cli]" 2>&1 | tee -a "$LOG_FILE"
fi

log "hf CLI version: $(hf version 2>&1)"
log "Logged in as:   $(hf auth whoami 2>&1 || echo 'not logged in')"
log "Cache dir:      $(hf cache info 2>&1 | head -1 || echo '~/.cache/huggingface/hub')"

# ── Step 1/4 ─────────────────────────────────────────────────
log_step "Step 1/4: GAIR/daVinci-MagiHuman (~144 GB)"
log "  Downloading: base (~28.5 GB), distill (~57 GB), 1080p_sr (~57 GB), turbo_vae (~1.7 GB)"
log "  Skipping:    540p_sr (1080p SR covers this)"
step_start

MAGIHUMAN_PATH=$(hf download GAIR/daVinci-MagiHuman \
    --include "base/*" "distill/*" "1080p_sr/*" "turbo_vae/*" "config.json" \
    2>&1 | tee -a "$LOG_FILE" | tail -1)

log "Step 1/4 complete. Elapsed: $(step_elapsed)"
log "Cached at: $MAGIHUMAN_PATH"

# ── Step 2/4 ─────────────────────────────────────────────────
log_step "Step 2/4: T5Gemma-9B text encoder (~18 GB)"
step_start

T5GEMMA_PATH=$(hf download google/t5gemma-9b-9b-ul2 \
    2>&1 | tee -a "$LOG_FILE" | tail -1)

log "Step 2/4 complete. Elapsed: $(step_elapsed)"
log "Cached at: $T5GEMMA_PATH"

# ── Step 3/4 ─────────────────────────────────────────────────
log_step "Step 3/4: Stable Audio Open 1.0 (~3-4 GB)"
step_start

STABLE_AUDIO_PATH=$(hf download stabilityai/stable-audio-open-1.0 \
    2>&1 | tee -a "$LOG_FILE" | tail -1)

log "Step 3/4 complete. Elapsed: $(step_elapsed)"
log "Cached at: $STABLE_AUDIO_PATH"

# ── Step 4/4 ─────────────────────────────────────────────────
log_step "Step 4/4: Wan2.2-TI2V-5B VAE (~10-15 GB)"
step_start

WAN_VAE_PATH=$(hf download Wan-AI/Wan2.2-TI2V-5B \
    2>&1 | tee -a "$LOG_FILE" | tail -1)

log "Step 4/4 complete. Elapsed: $(step_elapsed)"
log "Cached at: $WAN_VAE_PATH"

# ── Save paths ───────────────────────────────────────────────
cat > "$PATHS_FILE" <<EOF
# Auto-generated by setup.sh on $(ts)
# Source this file or use these paths in config
MAGIHUMAN_PATH=$MAGIHUMAN_PATH
T5GEMMA_PATH=$T5GEMMA_PATH
STABLE_AUDIO_PATH=$STABLE_AUDIO_PATH
WAN_VAE_PATH=$WAN_VAE_PATH
EOF

log ""
log "Model paths saved to: $PATHS_FILE"

# ── Generate config ──────────────────────────────────────────
log "Generating MPS config files with resolved paths..."

cat > "$PROJECT_ROOT/example/mps_distill/config.json" <<EOF
{
  "engine_config": {
    "load": "$MAGIHUMAN_PATH/distill",
    "distill": true,
    "cp_size": 1,
    "distributed_backend": "gloo"
  },
  "evaluation_config": {
    "cfg_number": 1,
    "num_inference_steps": 8,
    "audio_model_path": "$STABLE_AUDIO_PATH",
    "txt_model_path": "$T5GEMMA_PATH",
    "vae_model_path": "$WAN_VAE_PATH",
    "use_turbo_vae": true,
    "student_config_path": "$MAGIHUMAN_PATH/turbo_vae/TurboV3-Wan22-TinyShallow_7_7.json",
    "student_ckpt_path": "$MAGIHUMAN_PATH/turbo_vae/checkpoint-340000.ckpt"
  }
}
EOF

cat > "$PROJECT_ROOT/example/mps_1080p/config.json" <<EOF
{
  "engine_config": {
    "load": "$MAGIHUMAN_PATH/distill",
    "distill": true,
    "cp_size": 1,
    "distributed_backend": "gloo"
  },
  "evaluation_config": {
    "cfg_number": 1,
    "num_inference_steps": 8,
    "audio_model_path": "$STABLE_AUDIO_PATH",
    "txt_model_path": "$T5GEMMA_PATH",
    "vae_model_path": "$WAN_VAE_PATH",
    "use_sr_model": true,
    "sr_model_path": "$MAGIHUMAN_PATH/1080p_sr",
    "sr_num_inference_steps": 5,
    "sr_cfg_number": 1,
    "use_turbo_vae": true,
    "student_config_path": "$MAGIHUMAN_PATH/turbo_vae/TurboV3-Wan22-TinyShallow_7_7.json",
    "student_ckpt_path": "$MAGIHUMAN_PATH/turbo_vae/checkpoint-340000.ckpt"
  }
}
EOF

log "Configs updated with HF cache paths"

# ── Summary ──────────────────────────────────────────────────
log_header "All downloads complete! Total time: $(total_elapsed)"
log ""
log "Model paths:"
log "  MagiHuman:    $MAGIHUMAN_PATH"
log "  T5Gemma:      $T5GEMMA_PATH"
log "  Stable Audio: $STABLE_AUDIO_PATH"
log "  Wan VAE:      $WAN_VAE_PATH"
log ""
log "To run inference:"
log "  source .venv/bin/activate"
log "  python run_inference.py \\"
log "    --prompt 'Your prompt here' \\"
log "    --image_path example/assets/image.png \\"
log "    --seconds 4"
